-- 狐狸：角色和动画的例子（claude/animation.md）。由构建转译为 fox.lua：改这个文件。
-- 每个有狐狸的关卡脚本都引入它：
--     令 狐狸模块 = 引入("assets/characters/fox")
--
-- 跟着一个目标（通常是玩家）：离得远就跑过去，近了就走，到了身边就停下张望。和玩家一样用 角色移动 走在碰撞上，
-- 竖直速度存在它的 velocity 里。状态是一串条件，从上往下第一个成立的算数（claude/gameplay.md）。每次更新采样一个
-- 片段输出；换了片段，引擎自己从刚才的姿态过渡过去（惯性化），所以脚本什么都不用记：要知道"刚才在跑吗"，就问
-- 动画.播放中。
--
-- 模块不保存状态（CLAUDE.md：Lua 从不保存状态）：句柄由关卡脚本在 世界.开始 里取好传进来。

local 狐狸模块 = {}

local 上 = 矢量3(0, 1, 0)

local 半径 = 0.08
local 身高 = 0.25
local 走速 = 0.6   -- 米每秒
local 跑速 = 1.8
local 转速 = 8     -- 朝向追上移动方向的快慢
local 重力 = 5.0   -- 和玩家一样

-- 片段按 速度 播放的倍率。导入时片段被做成原地播放，记下了它原本走多快（移动速度），按它播放脚就不滑；
-- 原地制作的片段没有这个速度，就照常播放。
local function 播放倍率(狐狸, 片段, 速度)
    local 原速 = 动画.移动速度(狐狸, 片段)
    if 原速 > 0 then return 速度 / 原速 end
    return 1
end

-- 在 世界.更新 里每次调用。目标：跟着谁走。
function 狐狸模块.更新(狐狸, 目标, 时间差)
    if not 实体.有效(狐狸) or not 实体.有效(目标) then return end
    local 位置 = 实体.取位置(狐狸)
    local 目标位置 = 实体.取位置(目标)
    local 方向 = 矢量3(目标位置.x - 位置.x, 0, 目标位置.z - 位置.z)
    local 距离 = 方向:长度()

    -- 跑起来后要近一点才慢下来，停下张望后要远一点才再走，免得在边界上来回切换。
    local 跑的距离 = 动画.播放中(狐狸, "Run") and 2.5 or 3
    local 走的距离 = 动画.播放中(狐狸, "Survey") and 1.2 or 0.8

    local 速度, 姿态 = 0, nil
    if 距离 > 跑的距离 then
        速度 = 跑速
        姿态 = 动画.采样(狐狸, "Run", 播放倍率(狐狸, "Run", 速度))
    elseif 距离 > 走的距离 then
        速度 = 走速
        姿态 = 动画.采样(狐狸, "Walk", 播放倍率(狐狸, "Walk", 速度))
    else
        姿态 = 动画.采样(狐狸, "Survey")
    end
    动画.输出(狐狸, 姿态)

    -- 移动和重力，同玩家。
    local 水平 = 矢量3(0, 0, 0)
    if 速度 > 0 then 水平 = 方向 * (速度 / 距离) end
    local 竖直 = 实体.取矢量(狐狸, "velocity").y - 重力 * 时间差
    local 着地 = 实体.角色移动(狐狸, 矢量3(水平.x * 时间差, 竖直 * 时间差, 水平.z * 时间差), 半径, 身高)
    if 着地 and 竖直 < 0 then 竖直 = -0.1 end
    实体.设矢量(狐狸, "velocity", 矢量3(0, 竖直, 0))
    if 实体.取位置(狐狸).y < 目标位置.y - 5 then   -- 掉出了世界：回到目标身边
        实体.设位置(狐狸, 目标位置 + 矢量3(0.5, 0.2, 0))
        实体.设矢量(狐狸, "velocity", 矢量3(0, 0, 0))
    end

    -- 转向：朝向存在实体上，每次往目标的方向转一点。
    if 距离 > 0.01 then
        local 想朝 = 四元数.轴角(上, 数学.反正切2(方向.x, 方向.z))
        实体.设朝向(狐狸, 实体.取朝向(狐狸):球面插值(想朝, 数学.截断(转速 * 时间差)))
    end
end

-- 在 世界.动画事件 里调用。动画事件是片段里标好的时刻（assets/characters/Fox.clips），在片段播过它的那次更新之后到达；
-- 不是这只狐狸的事件就忽略，所以关卡脚本可以把每个事件都转过来。
function 狐狸模块.动画事件(狐狸, 实体号, 名字)
    if 实体号 == 狐狸 and 名字 == "footstep" then
        世界.在位置播放声音("assets/sounds/footstep.wav", 实体.取位置(狐狸), 0.35)
    end
end

return 狐狸模块
