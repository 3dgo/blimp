-- 玩家：走、跑、跳、转视角，以及从一个关卡走进另一个关卡。由构建转译为 player.lua：改这个文件。
-- 每个有玩家的关卡脚本都引入它：
--     令 玩家模块 = 引入("assets/characters/player")
--
-- "玩家" 是关卡里一个不画的实体（胶囊站在它的 position 上），"主相机" 跟在它的眼睛处。每个关卡各放一个，所以
-- 哪个关卡都能直接按运行来试。玩家实体的 scale.x 是它的大小：下面的数都是 scale 为 1 时的（城堡里的小人），
-- 真人大小的关卡把玩家的 scale 调大，速度、跳跃、重力跟着一起放大，手感不变。
--
-- 模块不保存状态（CLAUDE.md：Lua 从不保存状态）：句柄由关卡脚本在 世界.开始 里取好传进来，竖直速度存在玩家的
-- velocity 字段里，要带到下一关的东西存在 游戏 表里。

local 玩家模块 = {}

local 上 = 矢量3(0, 1, 0)
local 右 = 矢量3(1, 0, 0)
local 前 = 矢量3(0, 0, 1)

local 半径     = 0.08
local 身高     = 0.4
local 眼高     = 0.34
local 走速     = 1.0
local 跑速     = 2.0
local 跳速     = 1.6
local 重力     = 5.0
local 灵敏度   = 0.003   -- 每像素的弧度
local 摇杆看速 = 2.5     -- 每秒的弧度
local 步距时间 = 0.32    -- 走路时一步的秒数
local 入口键   = "入口"  -- 游戏 表里的键：下一关的玩家从哪个实体出现
local 出口颜色 = 矢量4(0.35, 0.9, 0.55, 1)

-- 这一帧越过了 间隔 的整数倍。
local function 越过(t, 时间差, 间隔)
    return 数学.向下取整(t / 间隔) ~= 数学.向下取整((t - 时间差) / 间隔)
end

-- 实体的体积盒子（Size，以实体为中心、随实体旋转）的 12 条边，画进游戏画面。
local function 画盒子(实体号, 颜色)
    local 中心 = 实体.取位置(实体号)
    local 朝向 = 实体.取朝向(实体号)
    local 半 = 实体.取矢量(实体号, "size") * 0.5
    local function 角(x, y, z)
        return 中心 + 朝向:旋转(矢量3(x * 半.x, y * 半.y, z * 半.z))
    end
    for a = -1, 1, 2 do
        for b = -1, 1, 2 do
            世界.调试线(角(-1, a, b), 角(1, a, b), 颜色)
            世界.调试线(角(a, -1, b), 角(a, 1, b), 颜色)
            世界.调试线(角(a, b, -1), 角(a, b, 1), 颜色)
        end
    end
end

-- 在 世界.开始 里调用。从另一个关卡过来时（游戏 表里有 入口），先把玩家放到那个入口实体上、朝它的方向；
-- 直接按运行时没有入口，玩家就在关卡里摆的位置。然后相机从玩家的朝向开始，锁定鼠标。
function 玩家模块.开始(玩家, 相机)
    if not 实体.有效(玩家) or not 实体.有效(相机) then return end
    local 入口名 = 游戏.取文本(入口键)
    if 入口名 ~= "" then
        local 入口 = 世界.获取(入口名)
        if 实体.有效(入口) then
            实体.设位置(玩家, 实体.取位置(入口))
            实体.设朝向(玩家, 实体.取朝向(入口))
            实体.设矢量(玩家, "velocity", 矢量3(0, 0, 0))
        end
        游戏.设文本(入口键, "")   -- 用掉了：热重载重跑 开始 时不会再把玩家拉回入口
    end
    实体.设朝向(相机, 实体.取朝向(玩家))
    输入.锁定鼠标(true)
end

-- 在 世界.更新 里每次调用。出生点：掉出世界后回到哪里。
function 玩家模块.更新(玩家, 相机, t, 时间差, 出生点)
    if not 实体.有效(玩家) or not 实体.有效(相机) then return end
    local 大小 = 实体.取缩放(玩家).x

    if 输入.按下("Escape") then   -- 暂停，放开鼠标好点暂停菜单（玩家模块.界面）
        世界.设暂停(true)
        输入.锁定鼠标(false)
    end
    if 输入.鼠标按下(1) then 输入.锁定鼠标(true) end

    -- 视角：从相机现在的朝向算出偏航和俯仰（正 = 向下看），加上这一帧的鼠标 / 摇杆。
    local 朝前 = 实体.取朝向(相机):旋转(前)
    local 鼠标 = 输入.鼠标移动()
    local 偏航 = 数学.反正切2(朝前.x, 朝前.z) + 鼠标.x * 灵敏度 + 输入.手柄轴("rightx") * 摇杆看速 * 时间差
    local 俯仰 = -数学.反正弦(数学.夹紧(朝前.y, -1, 1)) + 鼠标.y * 灵敏度 + 输入.手柄轴("righty") * 摇杆看速 * 时间差
    俯仰 = 数学.夹紧(俯仰, -1.4, 1.4)
    local 朝向 = 四元数.轴角(上, 偏航) * 四元数.轴角(右, 俯仰)

    -- 移动：沿偏航的水平方向。
    local 向前 = 矢量3(数学.正弦(偏航), 0, 数学.余弦(偏航))
    local 向右 = 矢量3(数学.余弦(偏航), 0, -数学.正弦(偏航))
    local 前后 = -输入.手柄轴("lefty")
    local 左右 = 输入.手柄轴("leftx")
    if 输入.按住("W") then 前后 = 前后 + 1 end
    if 输入.按住("S") then 前后 = 前后 - 1 end
    if 输入.按住("D") then 左右 = 左右 + 1 end
    if 输入.按住("A") then 左右 = 左右 - 1 end
    local 长 = 数学.开方(前后 * 前后 + 左右 * 左右)
    if 长 > 1 then
        前后 = 前后 / 长
        左右 = 左右 / 长
    end
    local 速度 = 走速
    if 输入.按住("Left Shift") or 输入.手柄按住("leftstick") then 速度 = 跑速 end
    local 水平 = (向前 * 前后 + 向右 * 左右) * (速度 * 大小)

    -- 重力和跳跃：竖直速度是 玩家 的 velocity.y。站在地上时轻轻压住地面，好让下一帧还算着地。
    local 竖直 = 实体.取矢量(玩家, "velocity").y - 重力 * 大小 * 时间差
    local 着地 = 实体.角色移动(玩家, 矢量3(水平.x * 时间差, 竖直 * 时间差, 水平.z * 时间差), 半径 * 大小, 身高 * 大小)
    if 着地 and 竖直 < 0 then 竖直 = -0.1 * 大小 end
    if 着地 and (输入.按下("Space") or 输入.手柄按下("a")) then
        竖直 = 跳速 * 大小
        世界.播放声音("assets/sounds/jump.wav", 0.5)
    end
    实体.设矢量(玩家, "velocity", 矢量3(0, 竖直, 0))

    local 位置 = 实体.取位置(玩家)
    if 位置.y < 出生点.y - 5 * 大小 then   -- 掉出了世界：回到出生点
        位置 = 出生点
        实体.设位置(玩家, 位置)
        实体.设矢量(玩家, "velocity", 矢量3(0, 0, 0))
    end
    local 眼 = 位置 + 上 * (眼高 * 大小)
    实体.设位置(相机, 眼)
    实体.设朝向(相机, 朝向)

    -- 脚步声：在地上走动时每 步距时间 一步，跑时按速度加快。
    if 着地 and 长 > 0.1 and 越过(t, 时间差, 步距时间 * 走速 / 速度) then
        世界.在位置播放声音("assets/sounds/footstep.wav", 位置, 0.7)
    end

    -- 射线检测：沿视线 8 个身位。
    if 输入.按下("E") or 输入.手柄按下("x") then
        local 命中, 点, 法线, 实体号 = 世界.射线检测(眼, 朝向:旋转(前), 8 * 大小)
        if 命中 then
            世界.在位置播放声音("assets/sounds/ping.wav", 点)
            打印("射线命中 " .. 实体.取文本(实体号, "name") .. " " .. 转文本(点))
        end
    end
end

-- 在 世界.更新 里每次调用，每个出口一次。触发器是一个“体积”设为触发区的实体；玩家身体的中点进了它的盒子，就记下 入口
-- （下一关里一个实体的名字，玩家从那里出现），切换到 关卡。触发区在游戏里也画出来，好让人看见出口在哪。
-- 入口别放在那边出口的盒子里，不然一到就又被送回去。
function 玩家模块.出口(玩家, 触发器, 关卡, 入口)
    if not 实体.有效(触发器) then return end
    画盒子(触发器, 出口颜色)
    if not 实体.有效(玩家) then return end
    -- 测身体的中点，不测脚底：站着时脚底会压到地面下一点点，贴地摆的盒子就测不到了。
    local 中点 = 实体.取位置(玩家) + 上 * (身高 * 实体.取缩放(玩家).x * 0.5)
    if 实体.包含(触发器, 中点) then
        游戏.设文本(入口键, 入口)
        世界.切换关卡(关卡)
    end
end

-- 在 世界.界面 里调用。暂停时（Esc，或编辑器里按 F6）在画面中间画暂停菜单；暂停时 世界.更新 不执行，所以继续只能在这里。
function 玩家模块.界面()
    if not 世界.已暂停() then return end
    界面.窗口开始("暂停", 0.5, 0.5)
    if 界面.按钮("继续") then
        世界.设暂停(false)
        输入.锁定鼠标(true)
    end
    界面.窗口结束()
end

return 玩家模块
