-- 城堡关卡的世界脚本（assets/scenes/castle.level），只在运行（Play）时执行。
-- 由构建转译为 castle.lua（关卡引用的是它）：改这个文件，不要改 castle.lua。
--
-- 这里每个姿态都是 世界.时间() 的函数（运行世界的游戏时钟，暂停时停止），所以脚本不保存状态
-- （CLAUDE.md：Lua 从不保存状态）。关卡里固定的部件在 世界.开始 里取一次句柄（每次运行、每次热重载
-- 都会重新取），之后直接用；旗帜按编号查找，找不到就是数完了。
-- 会动的实体只设为 Renderable（不是 Static / Cast Indirect），所以探针烘焙会忽略它们。

local 上 = 矢量3(0, 1, 0)
local 右 = 矢量3(1, 0, 0)
local 前 = 矢量3(0, 0, 1)

-- 固定部件的句柄，世界.开始 里用 世界.获取 取（找不到会警告）。
local 吊桥, 闸门, 探照灯, 城门声, 玩家, 相机, 狐狸

local function 平滑(x)
    x = 数学.截断(x)
    return x * x * (3 - 2 * x)
end

-- 城门循环，0 = 关闭并升起，1 = 打开并放下：开 6 秒，关闭 2 秒，关 5 秒，打开 2 秒。
local function 城门开度(t)
    local p = t % 15
    if p < 6  then return 1 end
    if p < 8  then return 1 - 平滑((p - 6) / 2) end
    if p < 13 then return 0 end
    return 平滑((p - 13) / 2)
end

local function 更新城门(t)
    local 开度 = 城门开度(t)
    local 朝向 = 四元数.轴角(上, 数学.圆周率 / 2)   -- 城门朝 -Z（它的套件部件偏航了 90 度）

    -- 吊桥：铰链在原点，沿本地 +X 平放；升起时绕本地 Z 把 +X 往上转。
    if 实体.有效(吊桥) then
        实体.设朝向(吊桥, 朝向 * 四元数.轴角(前, (1 - 开度) * 数学.角度转弧度(80)))
    end

    -- 闸门：城门打开时从拱门里升起（在吊桥放下之前先升）。
    if 实体.有效(闸门) then
        local 位置 = 实体.取位置(闸门)
        实体.设位置(闸门, 矢量3(位置.x, 平滑(开度 * 1.5) * 0.6, 位置.z))
    end
end

-- 主塔的探照灯扫过庭院和城门前的空地。
local function 更新探照灯(t)
    if not 实体.有效(探照灯) then return end
    local 偏航 = 数学.圆周率 + 数学.正弦(t * 0.5) * 数学.角度转弧度(70)
    实体.设朝向(探照灯, 四元数.轴角(上, 偏航) * 四元数.轴角(右, 数学.角度转弧度(38)))
end

-- 旗帜飘动，彼此错开节奏。
local function 更新旗帜(t)
    local i = 1
    while true do
        local 旗 = 世界.查找("旗帜_" .. i)
        if not 实体.有效(旗) then break end
        local 摆动 = 数学.正弦(t * 2.3 + i * 1.7) * 0.35 + 数学.正弦(t * 5.1 + i) * 0.08
        实体.设朝向(旗, 四元数.轴角(上, 摆动))
        i = i + 1
    end
end

-- 光源组（世界设置）：信标闪烁，大厅的窗户每 20 秒里暗 4 秒。
local function 更新灯光(t)
    世界.设光源组("beacon", 0.55 + 0.45 * 数学.正弦(t * 3))
    世界.设光源组("windows", (t % 20) < 16 and 1 or 0)
end

-- 城门开关时的声音：城门声 实体（城门处，Positional）。越过 = 这一帧越过了 间隔 的整数倍。
local function 越过(t, 时间差, 间隔)
    return 数学.向下取整(t / 间隔) ~= 数学.向下取整((t - 时间差) / 间隔)
end

local function 更新城门声音(t, 时间差)
    if 越过(t - 6, 时间差, 15) or 越过(t - 13, 时间差, 15) then   -- 开始关闭 / 开始打开（城门开度）
        实体.播放声音(城门声)
    end
end

-- ── 玩家：测试碰撞、输入和声音 ──
-- 第一人称。WASD / 左摇杆走，左 Shift / 按下左摇杆跑，鼠标 / 右摇杆看，空格 / A 跳，E / X 沿视线射线检测
-- （命中处响一声，控制台打印命中的实体），Esc 放开鼠标，左键再锁定。输入只在游戏模式（运行后）有效。
-- "玩家" 是一个不画的胶囊，站在它的 position 上；"主相机" 跟在它的眼睛处。竖直速度存在 玩家 的
-- velocity 字段里（Lua 不保存状态）。碰撞看每个实体的 collision 字段：城墙、塔楼、地面用渲染网格，
-- 树和石头用包围盒，旗子和轮子没有；吊桥和闸门不是 Static，会跟着脚本移动并挡住玩家。
local 玩家半径 = 0.08
local 玩家身高 = 0.4
local 眼高     = 0.34
local 走速     = 1.0
local 跑速     = 2.0
local 跳速     = 1.6
local 重力     = 5.0
local 灵敏度   = 0.003   -- 每像素的弧度
local 摇杆看速 = 2.5     -- 每秒的弧度
local 出生点   = 矢量3(0, 0.05, -6)
local 步距时间 = 0.32    -- 走路时一步的秒数

local function 更新玩家(t, 时间差)
    if not 实体.有效(玩家) or not 实体.有效(相机) then return end

    if 输入.按下("Escape") then 输入.锁定鼠标(false) end
    if 输入.鼠标按下(1) then 输入.锁定鼠标(true) end

    -- 视角：从相机现在的朝向算出偏航和俯仰（正 = 向下看），加上这一帧的鼠标 / 摇杆。
    local 朝前 = 实体.取朝向(相机):旋转(前)
    local 鼠标 = 输入.鼠标移动()
    local 偏航 = 数学.反正切2(朝前.x, 朝前.z) + 鼠标.x * 灵敏度 + 输入.手柄轴("rightx") * 摇杆看速 * 时间差
    local 俯仰 = -数学.反正弦(数学.夹紧(朝前.y, -1, 1)) + 鼠标.y * 灵敏度 + 输入.手柄轴("righty") * 摇杆看速 * 时间差
    俯仰 = 数学.夹紧(俯仰, -1.4, 1.4)
    local 朝向 = 四元数.轴角(上, 偏航) * 四元数.轴角(右, 俯仰)

    -- 移动：沿偏航的水平方向。
    local 向前 = 矢量3(数学.正弦(偏航), 0, 数学.余弦(偏航))
    local 向右 = 矢量3(数学.余弦(偏航), 0, -数学.正弦(偏航))
    local 前后 = -输入.手柄轴("lefty")
    local 左右 = 输入.手柄轴("leftx")
    if 输入.按住("W") then 前后 = 前后 + 1 end
    if 输入.按住("S") then 前后 = 前后 - 1 end
    if 输入.按住("D") then 左右 = 左右 + 1 end
    if 输入.按住("A") then 左右 = 左右 - 1 end
    local 长 = 数学.开方(前后 * 前后 + 左右 * 左右)
    if 长 > 1 then
        前后 = 前后 / 长
        左右 = 左右 / 长
    end
    local 速度 = 走速
    if 输入.按住("Left Shift") or 输入.手柄按住("leftstick") then 速度 = 跑速 end
    local 水平 = (向前 * 前后 + 向右 * 左右) * 速度

    -- 重力和跳跃：竖直速度是 玩家 的 velocity.y。站在地上时轻轻压住地面，好让下一帧还算着地。
    local 竖直 = 实体.取矢量(玩家, "velocity").y - 重力 * 时间差
    local 着地 = 实体.角色移动(玩家, 矢量3(水平.x * 时间差, 竖直 * 时间差, 水平.z * 时间差), 玩家半径, 玩家身高)
    if 着地 and 竖直 < 0 then 竖直 = -0.1 end
    if 着地 and (输入.按下("Space") or 输入.手柄按下("a")) then
        竖直 = 跳速
        世界.播放声音("assets/sounds/jump.wav", 0.5)
    end
    实体.设矢量(玩家, "velocity", 矢量3(0, 竖直, 0))

    local 位置 = 实体.取位置(玩家)
    if 位置.y < -5 then   -- 掉出了世界：回到出生点
        位置 = 出生点
        实体.设位置(玩家, 位置)
        实体.设矢量(玩家, "velocity", 矢量3(0, 0, 0))
    end
    local 眼 = 位置 + 上 * 眼高
    实体.设位置(相机, 眼)
    实体.设朝向(相机, 朝向)

    -- 脚步声：在地上走动时每 步距时间 一步，跑时按速度加快。
    if 着地 and 长 > 0.1 and 越过(t, 时间差, 步距时间 * 走速 / 速度) then
        世界.在位置播放声音("assets/sounds/footstep.wav", 位置, 0.7)
    end

    -- 射线检测：沿视线 8 个单位。
    if 输入.按下("E") or 输入.手柄按下("x") then
        local 命中, 点, 法线, 实体号 = 世界.射线检测(眼, 朝向:旋转(前), 8)
        if 命中 then
            世界.在位置播放声音("assets/sounds/ping.wav", 点)
            打印("射线命中 " .. 实体.取文本(实体号, "name") .. " " .. 转文本(点))
        end
    end
end

-- ── 狐狸：角色和动画的例子（claude/animation.md）──
-- 跟着玩家：离得远就跑过去，近了就走，到了身边就停下张望。和玩家一样用 角色移动 走在碰撞上，竖直速度存在它的
-- velocity 里。状态是一串条件，从上往下第一个成立的算数（claude/gameplay.md）。每次更新采样一个片段输出；换了
-- 片段，引擎自己从刚才的姿态过渡过去（惯性化），所以脚本什么都不用记：要知道"刚才在跑吗"，就问 动画.播放中。
local 狐狸半径 = 0.08
local 狐狸身高 = 0.25
local 狐狸走速 = 0.6   -- 米每秒
local 狐狸跑速 = 1.8
local 狐狸转速 = 8     -- 朝向追上移动方向的快慢

-- 片段按 速度 播放的倍率。导入时片段被做成原地播放，记下了它原本走多快（移动速度），按它播放脚就不滑；
-- 原地制作的片段没有这个速度，就照常播放。
local function 播放倍率(片段, 速度)
    local 原速 = 动画.移动速度(狐狸, 片段)
    if 原速 > 0 then return 速度 / 原速 end
    return 1
end

local function 更新狐狸(时间差)
    if not 实体.有效(狐狸) or not 实体.有效(玩家) then return end
    local 位置 = 实体.取位置(狐狸)
    local 目标 = 实体.取位置(玩家)
    local 方向 = 矢量3(目标.x - 位置.x, 0, 目标.z - 位置.z)
    local 距离 = 方向:长度()

    -- 跑起来后要近一点才慢下来，停下张望后要远一点才再走，免得在边界上来回切换。
    local 跑的距离 = 动画.播放中(狐狸, "Run") and 2.5 or 3
    local 走的距离 = 动画.播放中(狐狸, "Survey") and 1.2 or 0.8

    local 速度, 姿态 = 0, nil
    if 距离 > 跑的距离 then
        速度 = 狐狸跑速
        姿态 = 动画.采样(狐狸, "Run", 播放倍率("Run", 速度))
    elseif 距离 > 走的距离 then
        速度 = 狐狸走速
        姿态 = 动画.采样(狐狸, "Walk", 播放倍率("Walk", 速度))
    else
        姿态 = 动画.采样(狐狸, "Survey")
    end
    动画.输出(狐狸, 姿态)

    -- 移动和重力，同玩家。
    local 水平 = 矢量3(0, 0, 0)
    if 速度 > 0 then 水平 = 方向 * (速度 / 距离) end
    local 竖直 = 实体.取矢量(狐狸, "velocity").y - 重力 * 时间差
    local 着地 = 实体.角色移动(狐狸, 矢量3(水平.x * 时间差, 竖直 * 时间差, 水平.z * 时间差), 狐狸半径, 狐狸身高)
    if 着地 and 竖直 < 0 then 竖直 = -0.1 end
    实体.设矢量(狐狸, "velocity", 矢量3(0, 竖直, 0))
    if 实体.取位置(狐狸).y < -5 then   -- 掉出了世界：回到玩家身边
        实体.设位置(狐狸, 目标 + 矢量3(0.5, 0.2, 0))
        实体.设矢量(狐狸, "velocity", 矢量3(0, 0, 0))
    end

    -- 转向：朝向存在实体上，每次往玩家的方向转一点。
    if 距离 > 0.01 then
        local 想朝 = 四元数.轴角(上, 数学.反正切2(方向.x, 方向.z))
        实体.设朝向(狐狸, 实体.取朝向(狐狸):球面插值(想朝, 数学.截断(狐狸转速 * 时间差)))
    end
end

-- 动画事件：片段里标好的时刻（assets/characters/Fox.events），在片段播过它的那次更新之后调用。
function 世界.动画事件(实体号, 名字)
    if 实体号 == 狐狸 and 名字 == "footstep" then
        世界.在位置播放声音("assets/sounds/footstep.wav", 实体.取位置(狐狸), 0.35)
    end
end

function 世界.开始()
    打印("castle.luacn: 开始")
    吊桥   = 世界.获取("吊桥")
    闸门   = 世界.获取("闸门")
    探照灯 = 世界.获取("探照灯")
    城门声 = 世界.获取("城门声")
    玩家   = 世界.获取("玩家")
    狐狸   = 世界.获取("狐狸")
    相机   = 世界.获取("主相机")

    -- 相机从玩家的朝向开始（关卡里的 主相机 是编辑器里的俯瞰视角）。
    if 实体.有效(玩家) and 实体.有效(相机) then
        实体.设朝向(相机, 实体.取朝向(玩家))
        输入.锁定鼠标(true)
    end
end

function 世界.更新(时间差)
    local t = 世界.时间()
    更新城门(t)
    更新城门声音(t, 时间差)
    更新探照灯(t)
    更新旗帜(t)
    更新灯光(t)
    更新玩家(t, 时间差)
    更新狐狸(时间差)
end
