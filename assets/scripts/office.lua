-- 维多利亚办公室的世界脚本（assets/scenes/victorian_office.level），只在运行（Play）时执行。
-- 由构建转译为 office.lua（关卡引用的是它）：改这个文件，不要改 office.lua。
--
-- 玩家和城堡里的是同一个模块（assets/characters/player），只是这里的 玩家 实体 scale 为 4，按真人大小走。
-- 从城堡过来时在 从城堡来 出现；西走廊尽头的绿盒子（回城堡，一个触发区）送你回城堡的 从办公室来。

local 玩家模块 = 引入("assets/characters/player")
local 出生点   = 矢量3(0, 0.05, -4)
local 金币模块 = 引入("assets/scripts/coins")   -- 和城堡共用，捡到的个数带到下一关

-- 固定部件的句柄，世界.开始 里用 世界.获取 取（找不到会警告）。
local 玩家, 相机, 回城堡

function 世界.开始()
    玩家   = 世界.获取("玩家")
    相机   = 世界.获取("主相机")
    回城堡 = 世界.获取("回城堡")
    玩家模块.开始(玩家, 相机)
    金币模块.开始("办公室")
end

function 世界.更新(时间差)
    玩家模块.更新(玩家, 相机, 世界.时间(), 时间差, 出生点)
    玩家模块.出口(玩家, 回城堡, "assets/scenes/castle.level", "从办公室来")
    金币模块.更新("办公室", 玩家, 世界.时间())
end

-- 屏幕界面：每帧都画，暂停时也画。
function 世界.界面()
    金币模块.界面()
    玩家模块.界面()
end
